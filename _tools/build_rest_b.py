def build(title, src, summary, claims, concepts, note):
    stem = f"{T}-{safe(title)}"
    L = ["---", "type: doc", f"title: {title}", f"source_path: raw/docs/{src}",
         "source_type: youdao", "modality: text", "confidence: 0.95",
         "compile_status: compiled", f"compiled_at: {T}", "---", "",
         f"# {title}", "", "## 摘要", "", summary, ""]
    if claims:
        L += ["## 关键断言", ""]
        for stmt, conf, ev in claims:
            L.append(f"- {stmt}  `{conf}`")
            L.append(f"  > 原文：「{ev}」")
            L.append("")
    else:
        L += ["## 关键断言", "", "（本篇为操作记录或清单，无可提炼的断言）", ""]
    if note:
        L += [f"> 注：{note}", ""]
    L += ["## 涉及概念", "", " · ".join(f"[[{c}]]" for c in concepts) if concepts else "（无）", "",
          "## 原文位置", "", f"`raw/docs/{src}`", ""]
    (DOCS / f"{stem}.md").write_text("\n".join(L), encoding="utf-8")
    return stem

def build_sensitive(title, src, why):
    stem = f"{T}-{safe(title)}（凭据已屏蔽）"
    L = ["---", "type: doc", f"title: {title}", f"source_path: raw/docs/{src}",
         "source_type: youdao", "modality: text", "confidence: 0.0",
         "compile_status: withheld", "sensitive: true", f"compiled_at: {T}", "---", "",
         f"# {title}（凭据已屏蔽）", "",
         "## 摘要", "",
         f"**本页不承载原文内容。** {why}，可能包含可被直接利用的访问凭据，因此：",
         "",
         "- 不进索引摘要",
         "- 不进概念网络",
         "- 不参与任何检索与问答",
         "",
         "原文仍在 `raw/docs/` 本地留存，需要时请直接打开文件，不要粘贴到任何模型对话中。", "",
         "## 关键断言", "", "（已屏蔽）", "",
         "## 涉及概念", "", "（已屏蔽）", "",
         "## 原文位置", "", f"`raw/docs/{src}`", ""]
    (DOCS / f"{stem}.md").write_text("\n".join(L), encoding="utf-8")
    return stem

