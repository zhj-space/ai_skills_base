def render(d):
    L = ["---", "type: concept", f"name: {d['name']}",
         f"aliases: [{', '.join(d['alias'])}]" if d['alias'] else "aliases: []", f"updated: {T}", "---", "", f"# {d['name']}", "",
         f"> {d['defi']}", "", "## 是什么", "", d["what"], "",
         "## 怎样理解 · 为什么", "", d["why"], "",
         "## 有什么性质", "", "| 性质 | 说明 |", "|---|---|"]
    for k, v in d["props"]:
        L.append(f"| {'**' + k + '**' if k == '边界' else k} | {v} |")
    L += ["", "## 怎么用", ""]
    for i, s in enumerate(d["how"], 1):
        L.append(f"{i}. {s}")
    L += ["", "## 关系", ""]
    for k in ["上位", "组成", "相关", "产出"]:
        arr = d["rel"].get(k) or []
        if arr:
            L.append(f"- {k}：" + " · ".join(f"[[{x}]]" for x in arr))
    L += ["", "## 常见误区", ""]
    for bad, good in d["pit"]:
        L.append(f"- ❌ {bad}")
        L.append(f"  ✅ {good}")
    L += ["", "## 出处", ""]
    for s in d["src"]:
        L.append(f"- [[{s}]]")
    L += [""]
    return "\n".join(L)

