made = []
for title, src, summary, claims, concepts in PAGES:
    stem = f"{TODAY}-{safe(title)}"
    L = ["---", "type: doc", f"title: {title}", f"source_path: raw/docs/{src}",
         "source_type: youdao", "modality: text", "confidence: 0.95",
         "compile_status: compiled", f"compiled_at: {TODAY}", "---", "",
         f"# {title}", "", "## 摘要", "", summary, "", "## 关键断言", ""]
    for stmt, conf, ev in claims:
        L.append(f"- {stmt}  `{conf}`")
        L.append(f"  > 原文：「{ev}」")
        L.append("")
    L += ["## 涉及概念", "", " · ".join(f"[[{c}]]" for c in concepts), "",
          "## 原文位置", "", f"`raw/docs/{src}`", ""]
